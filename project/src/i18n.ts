export function createT(lang: Language): TFn {
  return (key: string, vars?: Record<string, string>) => {
    let str = coreLocales[key]?.[lang];
    if (str === undefined) {
      str = translations[key]?.[langAlias[lang]] ?? key;
    }
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.split(`{${k}}`).join(v);
      }
    }
    return str;
  };
}

export const LangContext = createContext<TFn>((key) => key);

export function useT(): TFn {
  return useContext(LangContext);
}
